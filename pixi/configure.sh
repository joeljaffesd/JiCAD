#!/usr/bin/env bash
# Configure KiCad against the pixi environment ($CONDA_PREFIX) plus the locally built wx and ngspice.
set -euo pipefail
BUILD_TYPE="${KICAD_BUILD_TYPE:-RelWithDebInfo}"
cmake -S "$PIXI_PROJECT_ROOT" -B "$KICAD_BUILD_DIR" -G Ninja \
  -DCMAKE_BUILD_TYPE="$BUILD_TYPE" \
  -DCMAKE_C_COMPILER="$CC" -DCMAKE_CXX_COMPILER="$CXX" -DCMAKE_OSX_SYSROOT="$SDKROOT" \
  -DCMAKE_OSX_DEPLOYMENT_TARGET="$MACOSX_DEPLOYMENT_TARGET" \
  -DCMAKE_PREFIX_PATH="$CONDA_PREFIX;$KICAD_DEPS/wx;$KICAD_DEPS/ngspice" \
  -DCMAKE_INSTALL_PREFIX="$KICAD_BUILD_DIR/install" \
  -DCMAKE_CXX_FLAGS="${CXXFLAGS:-} -D_LIBCPP_DISABLE_AVAILABILITY" -DCMAKE_C_FLAGS="${CFLAGS:-}" \
  -DCMAKE_C_COMPILER_LAUNCHER=ccache -DCMAKE_CXX_COMPILER_LAUNCHER=ccache \
  -DwxWidgets_CONFIG_EXECUTABLE="$KICAD_DEPS/wx/bin/wx-config" \
  -DNGSPICE_INCLUDE_DIR="$KICAD_DEPS/ngspice/include" -DNGSPICE_LIBRARY="$KICAD_DEPS/ngspice/lib/libngspice.dylib" \
  -DOCC_INCLUDE_DIR="$CONDA_PREFIX/include/opencascade" -DOCC_LIBRARY_DIR="$CONDA_PREFIX/lib" \
  -DPython3_EXECUTABLE="$CONDA_PREFIX/bin/python3" -DPYTHON_EXECUTABLE="$CONDA_PREFIX/bin/python3" \
  -DKICAD_APPLE_RUNTIME_DEP_DIRS="$CONDA_PREFIX/lib;$KICAD_DEPS/wx/lib;$KICAD_DEPS/ngspice/lib" \
  -DKICAD_SCRIPTING_WXPYTHON=OFF -DKICAD_BUILD_I18N=OFF -DKICAD_BUILD_QA_TESTS=OFF -DKICAD_USE_SENTRY=OFF \
  "$@"
